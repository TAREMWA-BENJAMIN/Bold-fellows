								<p align="justify">
									The goal of the Ethical Hacking Training is to help you take pre-emptive measures against malicious attacks by attacking the system ; all the while staying within legal limits. This philosophy stems from the proven practice of trying to catch a thief, by thinking like a thief.
								</p>
                                <p align="justify">The CHFI course will give participants the necessary skills to identify an intruder’s footprints and to properly gather the necessary evidence to prosecute. Many of today’s top tools of the forensic trade will be taught during this course, including software, hardware and specialized techniques. </p>
                                <p align="justify">The need for businesses to become more efficient and integrated with one another, as well as the home user, has given way to a new type of criminal, the “cyber-criminal.” It is no longer a matter of “will your or-ganization be comprised (hacked)?” but, rather, “when?” Today’s battles between corporations, gov-ernments, and countries are no longer fought only in the typical arenas of boardrooms or battlefields using physical force.</p>
                                <p align="justify">Now the battlefield starts in the technical realm, which ties into most every facet of modern day life. If you or your organization requires the knowledge or skills to identify, track, and prosecute the cyber criminal, then this is the course for you. </p>
                                                               
