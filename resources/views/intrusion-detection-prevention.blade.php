								<p align="justify">
									This course is designed to give students practical, working knowledge in intrusion detection and traffic analysis. The students will gain an understanding of the workings of TCP/IP, methods of network traffic analysis and one popular network intrusion detection system Snort. 
								</p>
                                <p align="justify">The emphasis of this course is on increasing students’ understanding of the workings of TCP/IP, methods of network traffic analysis and one specific network intrusion detection system (NIDS) - Snort. Challenging, hands-on exercises are specially designed to be valuable for all experience levels. Delegates will install and commission the Snort Open Source IDS/IPS system on their own internal network and be trained in the management, monitoring and support of the system.  </p>
                                <p align="justify">On completion of the training, delegates will have a fully working intrusion detection and prevention system. They will be able to comprehensively evaluate the use of an IDS and IPS in a working environment and have the knowledge to deploy further units in a business or enterprise-wide environment.</p>
