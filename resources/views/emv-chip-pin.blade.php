								<p align="justify">
									Euro-pay, Master-card and VISA card security training is a course that allows for the technical management and staff to understand in details the EMV specifications and related chip security mechanisms. It will give delegates the right theoretical and practical knowledge to be key actors in the EMV migration process, and to define the issuer’s strategy in terms of card issuance.
								</p>
                                <p align="justify">A significant part of the training is dedicated to practical exercises, including creation of EMV test cards, and transaction simulations.  </p>
                                <p align="justify">Anti Money Laundering - Our global anti-money laundering training course, is aimed at clients who have Local, Regional or Global operations and a global anti-money laundering and counter terrorist financing policy. Those who take this course will be better able to recognize the how, what, where and why of money launderers and terrorist financiers targeting the financial system. They will better recognize their own responsibilities in detecting and preventing money laundering, and will understand the steps they can take to reduce those risks. </p>
