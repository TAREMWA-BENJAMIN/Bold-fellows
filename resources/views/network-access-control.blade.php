					<p>
						NAC is ideal for corporations and agencies where the user environment can be rigidly controlled. It is also called network admission control, a method of bolstering the security of a proprietary network by restricting the availability of network resources to endpoint devices that comply with a defined security policy.</p>
                        <p><strong>Mitigation of non-zero-day attacks:</strong> The main benefit of NAC solutions is to prevent end-stations that lack antivirus, patches, or host intrusion prevention software from accessing the network and placing other computers at risk of cross-contamination of computer worms.  </p>
                        <p><strong>Policy enforcement:</strong> NAC solutions allow network operators to define policies, such as the types of computers or roles of users allowed to access areas of the network, and enforce them in switches, routers, and network middleboxes.  </p>
<p><strong>Identity and access management:</strong> Where conventional IP networks enforce access policies in terms of IP addresses, NAC environments attempt to do so based on authenticated user identities, at least for user end-stations such as laptops and desktop computers. 
    
